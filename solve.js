const CONTINUED = /^ {2,}\S/;

/** The characters a backslash escapes. */
const ESCAPABLE = new Uint8Array(128);
for (const ch of ['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']) ESCAPABLE[ch.charCodeAt(0)] = 1;

/** A paragraph line as it is rendered: spaces and tabs at either end dropped. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

function isLangChar(c) {
  return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45;
}

/** A fence-open line's language, or null. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  while (j < line.length && isLangChar(line.charCodeAt(j))) j++;
  const lang = line.slice(3, j);
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  return j === line.length ? lang : null;
}

/** Whether `line` is a fence-close line. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  let j = 3;
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  return j === line.length;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6 || h >= line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let e = line.length;
  while (e > h && (line.charCodeAt(e - 1) === 32 || line.charCodeAt(e - 1) === 9)) e--;
  let s = h;
  while (s < e && (line.charCodeAt(s) === 32 || line.charCodeAt(s) === 9)) s++;
  if (s >= e) return null;
  return { depth: h, text: line.slice(s, e) };
}

/** Whether `line` is a thematic break. */
function isHr(line) {
  const c0 = line.charCodeAt(0);
  if (c0 !== 45 && c0 !== 42) return false;
  if (line.length < 3 || line.charCodeAt(1) !== c0 || line.charCodeAt(2) !== c0) return false;
  let j = 3;
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  return j === line.length;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  const c = line.charCodeAt(0);
  if (c === 35) return headingOf(line) !== null;
  if (c === 96) return fenceLang(line) !== null;
  if (c === 45 || c === 42) return isHr(line);
  if (c === 32 || c === 9 || Number.isNaN(c)) return isBlankLine(line);
  return false;
}

/** A bullet list line's item text, or null. */
function bulletOf(line) {
  const c0 = line.charCodeAt(0);
  if ((c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered list line's start and item text, or null. */
function orderedOf(line) {
  let j = 0;
  while (j < line.length && j < 9 && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
  if (j === 0 || j >= line.length) return null;
  if (line.charCodeAt(j) !== 46) return null;
  if (j + 1 >= line.length || line.charCodeAt(j + 1) !== 32) return null;
  return { start: Number(line.slice(0, j)), text: line.slice(j + 2) };
}

/** Whether the character at `j` is backslash-escaped: an odd run of backslashes before it, counted from `from`. */
function isEscaped(s, j, from) {
  let n = 0;
  for (let k = j - 1; k >= from && s.charCodeAt(k) === 92; k--) n++;
  return (n & 1) === 1;
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  let j = s.indexOf(what, from);
  while (j !== -1 && isEscaped(s, j, from)) j = s.indexOf(what, j + 1);
  return j;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  let j = s.indexOf('*', from);
  while (j !== -1) {
    if (isEscaped(s, j, from)) { j = s.indexOf('*', j + 1); continue; }
    if (s.charCodeAt(j + 1) === 42) { j = s.indexOf('*', j + 2); continue; }
    return j;
  }
  return -1;
}

/** The inline specials; exec finds the next one in C++ instead of a per-character JS loop. */
const INLINE_SPECIAL = /[\\`*[]/g;

/** `s` rendered inline into `out`; `env.link(target)` is a link's href. */
function inlineInto(s, env, out) {
  const re = INLINE_SPECIAL;
  const saved = re.lastIndex;
  re.lastIndex = 0;
  let start = 0;
  let m;
  while ((m = re.exec(s)) !== null) {
    const i = m.index;
    const c = m[0];
    if (c === '\\') {
      if (i + 1 < s.length && ESCAPABLE[s.charCodeAt(i + 1)] === 1) {
        if (i > start) pushEsc(s.slice(start, i), out);
        const ch = s[i + 1];
        out.push(ch === '>' ? '&gt;' : ch);
        start = i + 2;
        re.lastIndex = i + 2;
      } else re.lastIndex = i + 1;
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > start) pushEsc(s.slice(start, i), out);
        out.push('<code>');
        pushEsc(s.slice(i + 1, j), out);
        out.push('</code>');
        start = j + 1;
        re.lastIndex = j + 1;
      } else re.lastIndex = i + 1;
      continue;
    }
    if (c === '*') {
      if (s.charCodeAt(i + 1) === 42) {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (i > start) pushEsc(s.slice(start, i), out);
          out.push('<strong>');
          inlineInto(s.slice(i + 2, j), env, out);
          out.push('</strong>');
          start = j + 2;
          re.lastIndex = j + 2;
        } else re.lastIndex = i + 2;
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > start) pushEsc(s.slice(start, i), out);
        out.push('<em>');
        inlineInto(s.slice(i + 1, j), env, out);
        out.push('</em>');
        start = j + 1;
        re.lastIndex = j + 1;
      } else re.lastIndex = i + 1;
      continue;
    }
    const k = findUnescaped(s, ']', i + 1);
    const mm = k !== -1 && s.charCodeAt(k + 1) === 40 ? s.indexOf(')', k + 2) : -1;
    const target = mm === -1 ? '' : s.slice(k + 2, mm);
    if (target !== '' && !/\s/.test(target)) {
      if (i > start) pushEsc(s.slice(start, i), out);
      out.push('<a href="');
      pushEsc(env.link(target), out);
      out.push('">');
      inlineInto(s.slice(i + 1, k), env, out);
      out.push('</a>');
      start = mm + 1;
      re.lastIndex = mm + 1;
    } else re.lastIndex = i + 1;
  }
  if (s.length > start) pushEsc(s.slice(start), out);
  re.lastIndex = saved;
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of contents (every level 2
 * and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's inline HTML, or "").
 */
function renderMarkdown(src, env, slugCache) {
  const lines = src.split('\n');
  const out = [];
  const toc = [];
  const ids = new Set();
  let excerpt = null;
  let i = 0;
  const listBlock = (isOrdered, firstText, start) => {
    const items = [[trimLine(firstText)]];
    i++;
    while (i < lines.length) {
      if (isOrdered) {
        const m = orderedOf(lines[i]);
        if (m !== null) { items.push([trimLine(m.text)]); i++; continue; }
      } else {
        const m = bulletOf(lines[i]);
        if (m !== null) { items.push([trimLine(m)]); i++; continue; }
      }
      if (CONTINUED.test(lines[i])) { items[items.length - 1].push(trimLine(lines[i])); i++; continue; }
      break;
    }
    if (isOrdered && start !== 1) out.push(`<ol start="${start}">\n`);
    else out.push(isOrdered ? '<ol>\n' : '<ul>\n');
    for (let k = 0; k < items.length; k++) {
      out.push('<li>');
      inlineInto(items[k].join('\n'), env, out);
      out.push('</li>\n');
    }
    out.push(isOrdered ? '</ol>\n' : '</ul>\n');
  };
  while (i < lines.length) {
    const line = lines[i];
    // Dispatch on the first character: most lines start a paragraph, and a paragraph line can only
    // start with a character that opens no other block, so those skip every block test.
    const c0 = line.charCodeAt(0);
    if (c0 === 35) { // '#'
      const heading = headingOf(line);
      if (heading !== null) {
        const id = uniqueSlug(slugify(heading.text, slugCache), ids);
        const tmp = [];
        inlineInto(heading.text, env, tmp);
        const html = tmp.join('');
        if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
        out.push(`<h${heading.depth} id="${id}">`, html, `</h${heading.depth}>\n`);
        i++;
        continue;
      }
    } else if (c0 === 96) { // '`'
      const lang = fenceLang(line);
      if (lang !== null) {
        i++;
        out.push(lang === '' ? '<pre><code>' : `<pre><code class="language-${esc(lang)}">`);
        while (i < lines.length && !isFenceClose(lines[i])) {
          pushEsc(lines[i], out);
          out.push('\n');
          i++;
        }
        i++;
        out.push('</code></pre>\n');
        continue;
      }
    } else if (c0 === 45 || c0 === 42) { // '-' '*'
      if (isHr(line)) { out.push('<hr>\n'); i++; continue; }
      const b = bulletOf(line);
      if (b !== null) { listBlock(false, b, 1); continue; }
    } else if (c0 === 62) { // '>'
      const body = [];
      while (i < lines.length && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      const trimmed = [];
      for (let k = 0; k < body.length; k++) {
        const t = trimLine(body[k]);
        if (t !== '') trimmed.push(t);
      }
      if (trimmed.length === 0) out.push('<blockquote>\n</blockquote>\n');
      else {
        out.push('<blockquote>\n<p>');
        inlineInto(trimmed.join('\n'), env, out);
        out.push('</p>\n</blockquote>\n');
      }
      continue;
    } else if (c0 >= 48 && c0 <= 57) { // digit
      const o = orderedOf(line);
      if (o !== null) { listBlock(true, o.text, o.start); continue; }
    } else if (c0 === 32 || c0 === 9 || Number.isNaN(c0)) {
      if (isBlankLine(line)) { i++; continue; }
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    if (excerpt === null) {
      const tmp = [];
      inlineInto(text, env, tmp);
      const html = tmp.join('');
      excerpt = html;
      out.push('<p>', html, '</p>\n');
    } else {
      out.push('<p>');
      inlineInto(text, env, out);
      out.push('</p>\n');
    }
  }
  return { html: out.join(''), toc, excerpt: excerpt ?? '' };
}

